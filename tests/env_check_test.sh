#!/usr/bin/env bash
# Tests of the .env syntax check (ops/env_check.sh) and of where it runs (issue #18): ./deploy.sh
# preflight on .env.jetson and on the Jetson's .env, deploy.yml before the build,
# tests/jetson_smoke.sh; and of the TS_AUTHKEY left in a .env once tailscale is logged in.
# No Jetson, no Docker: deploy.sh's functions run against a fake `remote` in a scratch home.
#
#   tests/env_check_test.sh
# The greps below look for the literal text of the scripts, $variables included.
# shellcheck disable=SC2016
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
CHECK="$ROOT/ops/env_check.sh"
CANARY="CANARY0secret0value0never0printed"

passed=0
step() { printf '\n== %s\n' "$*"; }
ok() {
  passed=$((passed + 1))
  printf '   ok: %s\n' "$*"
}
fail() {
  printf '   FAIL: %s\n' "$*" >&2
  exit 1
}
# run <expected exit> <cmd...>: stdout and stderr together in $WORK/out
run() {
  local want="$1" got=0
  shift
  "$@" >"$WORK/out" 2>&1 || got=$?
  [[ "$got" == "$want" ]] || fail "$* exited $got, expected $want: $(head -c 600 "$WORK/out")"
}
out_has() { grep -qF -- "$1" "$WORK/out" || fail "output lacks '$1': $(head -c 600 "$WORK/out")"; }
no_secret() {
  if grep -q "$CANARY" "$WORK/out"; then fail "a value was printed: $(cat "$WORK/out")"; fi
}

# A .env as deploy.sh generates it, plus every form compose accepts that the check must let by.
# A base64 key with its = padding, made up here (44 characters, as openssl rand -base64 32).
FAKE_B64="$(printf 'A%.0s' {1..43})="
good="$WORK/good.env"
cat >"$good" <<EOF
# Production environment of the Jetson, generated by deploy.sh on 2026-10-10.
APP_ENV=production
SECRET_KEY=$CANARY
LOG_LEVEL=info

POSTGRES_PASSWORD=$CANARY
DATABASE_URL=postgresql+psycopg://jobapp:$CANARY@db:5432/jobapp?sslmode=disable
CREDENTIALS_KEY=$FAKE_B64
B64_TWO_PADS=YWJjZA==
   # an indented comment
EMPTY=
_UNDERSCORE_1=x
QUOTED_SPACES="a value with spaces = and equals"
SINGLE='it is \$NOT expanded = fine'
ESCAPED="say \"hi\" and \\\\ back"
EMPTY_QUOTED=""
INLINE=value # a comment after spaces
QUOTED_INLINE="v w" # comment
TS_HOSTNAME=jobapp
TS_AUTHKEY=
EOF
printf 'TRAILING_SPACES=ok   \n\t\nCRLF=ok\r\nNO_NEWLINE_AT_END=ok' >>"$good"

step "ops/env_check.sh: valid files pass silently"
run 0 "$CHECK" "$good"
[[ ! -s "$WORK/out" ]] || fail "output on a valid file: $(cat "$WORK/out")"
: >"$WORK/empty.env"
run 0 "$CHECK" "$WORK/empty.env"
printf '# only comments\n\n' >"$WORK/comments.env"
run 0 "$CHECK" "$WORK/comments.env"
ok "generated keys, base64 padding, quoted spaces and =, escapes, empty values, inline comments, CRLF, no final newline, empty and comment-only files"

step "the failure of 2026-10-10: grep output pasted into the .env"
broken="$WORK/broken.env"
{
  head -n 19 "$good"
  printf '1 matches in 1 files:\n'
  printf '.env.jetson:20:SECRET_KEY=%s\n' "$CANARY"
  printf 'AFTER=still read\n'
} >"$broken"
run 1 "$CHECK" "$broken" .env
out_has ".env: line 20: invalid (not KEY=VALUE)"
out_has ".env: line 21: invalid (the name before = is not a variable name"
out_has ".env: line 22: invalid (spaces or quotes in the value need the whole value in quotes)"
out_has ".env: 3 invalid line(s); docker compose would refuse this file"
no_secret
grep -qF "matches in" "$WORK/out" && fail "the line itself was printed"
grep -qF ".env.jetson:20" "$WORK/out" && fail "the line itself was printed"
ok "both pasted lines named by number (20, 21) with a reason, never their text or value; the next bad line too"

step "every other invalid form, one line each"
expect_invalid() { # expect_invalid <reason fragment> <line>
  printf 'GOOD=1\n%s\n' "$2" >"$WORK/one.env"
  run 1 "$CHECK" "$WORK/one.env" one
  out_has "one: line 2: invalid ($1"
  no_secret
}
expect_invalid "not KEY=VALUE" "JUSTAKEY"
expect_invalid "not KEY=VALUE" "$CANARY"
expect_invalid "the name before = is not" " LEADING=$CANARY"
expect_invalid "the name before = is not" "export KEY=$CANARY"
expect_invalid "the name before = is not" "1KEY=$CANARY"
expect_invalid "the name before = is not" "MY-KEY=$CANARY"
expect_invalid "the name before = is not" "KEY =$CANARY"
expect_invalid "the name before = is not" "=$CANARY"
expect_invalid "the name before = is not" "KÉY=$CANARY"
expect_invalid "spaces or quotes" "KEY= $CANARY"
expect_invalid "spaces or quotes" "KEY=$CANARY with spaces"
expect_invalid "spaces or quotes" "KEY=$CANARY\"quote"
expect_invalid "spaces or quotes" "KEY=it's"
expect_invalid "spaces or quotes" "KEY=\"$CANARY\"after"
expect_invalid "spaces or quotes" "KEY='$CANARY' trailing words"
expect_invalid "a double quote is not closed" "KEY=\"$CANARY"
expect_invalid "a double quote is not closed" "KEY=\"$CANARY\\\""
expect_invalid "a single quote is not closed" "KEY='$CANARY"
ok "bare word, leading space, export, digit first, dash, space before =, empty name, non-ASCII name, unquoted spaces or quotes, text after a closing quote, unclosed quotes (multi-line values)"

step "a \$ outside single quotes: compose interpolates it (review of PR #20)"
# shellcheck disable=SC2016 # literal $ in the lines under test
for line in 'A=a${B' 'A=a$B' 'A="a$B"' 'A="a${B"' 'A=${B:?err}' 'A=$' 'A=a$$$B' 'A="$$$x"'; do
  expect_invalid 'a $ outside single quotes is interpolated by compose' "$line"
done
# shellcheck disable=SC2016
for line in "A='a\$B'" "A='\${B'" 'A=a$$B' 'A="a$$B"' 'A=$$' 'A=x # a $comment'; do
  printf '%s\n' "$line" >"$WORK/dollar.env"
  run 0 "$CHECK" "$WORK/dollar.env"
done
ok "\${ unclosed, \$NAME, \${NAME:?}, a lone or odd \$ refused unquoted and in double quotes; single quotes, \$\$ and a \$ in a comment pass"
long="$(printf 'x%.0s' {1..20000})"
printf 'LONG=%s\nLONG_BAD=%s %s\n' "$long" "$long" "$CANARY" >"$WORK/long.env"
run 1 "$CHECK" "$WORK/long.env"
out_has "line 2: invalid"
no_secret
ok "a 20,000 character value: valid alone, invalid with a space, still never printed"

step "missing file, arguments, and the ways it is run"
run 2 "$CHECK" "$WORK/missing.env" .env
out_has ".env: missing or unreadable"
run 2 "$CHECK"
out_has "usage: ops/env_check.sh <file> [label]"
run 1 bash -s -- "$broken" remote.env <"$CHECK"
out_has "remote.env: line 20: invalid"
no_secret
if [[ -x /bin/bash ]]; then
  run 1 /bin/bash "$CHECK" "$broken" .env
  out_has ".env: line 21: invalid"
  run 0 /bin/bash "$CHECK" "$good"
fi
# Sourced, it only defines functions.
run 0 bash -c "source '$CHECK'; declare -F check_env_file >/dev/null && ! declare -F main >/dev/null"
[[ ! -s "$WORK/out" ]] || fail "sourcing printed: $(cat "$WORK/out")"
ok "missing file is exit 2; streamed to bash -s (how deploy.sh and the smoke run it on the Jetson); the system bash; sourced quietly"

# --- deploy.sh: the preflight checks and the TS_AUTHKEY warning --------------------------------
# The functions as deploy.sh defines them, `remote` replaced by a shell in a scratch Jetson home.
JHOME="$WORK/jetson"
mkdir -p "$JHOME/jobapp"
dfun() { # dfun <function> <args...> in a subshell with deploy.sh's definitions
  (
    eval "$(sed -n -e '/^info() {/p' -e '/^warn() {/p' -e '/^die() {/,/^}/p' \
      -e '/^AUTHKEY_RE=/p' -e '/^check_env_files() {/,/^}/p' \
      -e '/^warn_leftover_authkey() {/,/^}/p' deploy.sh)"
    # shellcheck disable=SC2329 # called by the evaluated functions
    remote() { (cd "$JHOME" && bash -c "$*"); }
    # shellcheck disable=SC2034 # read by the evaluated functions
    HOST=fakejetson RDIR=jobapp RDIR_Q=jobapp LOCAL_ENV="$WORK/local/.env.jetson"
    "$@"
  )
}
mkdir -p "$WORK/local"

step "deploy.sh preflight: .env.jetson and the Jetson's .env checked before anything changes"
grep -q '^  check_env_files "${1:-0}"$' deploy.sh || fail "preflight does not call check_env_files"
grep -q '^  preflight "$force_env"$' deploy.sh || fail "cmd_deploy does not pass --env to preflight"
cp "$good" "$WORK/local/.env.jetson"
cp "$good" "$JHOME/jobapp/.env"
run 0 dfun check_env_files 0
out_has ".env.jetson: syntax ok"
out_has "fakejetson:jobapp/.env: syntax ok"
cp "$broken" "$JHOME/jobapp/.env"
run 1 dfun check_env_files 0
out_has "fakejetson:jobapp/.env: line 20: invalid (not KEY=VALUE)"
out_has "has invalid lines (above): fix them there (./deploy.sh ssh) or replace the file with ./deploy.sh --env"
no_secret
run 0 dfun check_env_files 1
out_has "replaced by .env.jetson (--env), not checked"
cp "$broken" "$WORK/local/.env.jetson"
run 1 dfun check_env_files 1
out_has ".env.jetson: line 21: invalid"
out_has ".env.jetson has invalid lines (above): fix them before deploying"
no_secret
rm "$JHOME/jobapp/.env" "$WORK/local/.env.jetson"
run 0 dfun check_env_files 0
[[ ! -s "$WORK/out" ]] || fail "first deploy (no .env anywhere) printed: $(cat "$WORK/out")"
grep -q 'bash "$ROOT/ops/env_check.sh" "$LOCAL_ENV" .env.jetson || die' deploy.sh ||
  fail "push_env does not check a .env.jetson it just copied"
ok "valid files pass; a broken Jetson .env stops the deploy with the line number and no value, unless --env replaces it; a broken .env.jetson always stops it; nothing to check on a first deploy"

step "deploy.sh: TS_AUTHKEY left once the node is logged in is warned about, never printed"
grep -q '^  warn_leftover_authkey$' deploy.sh || fail "cmd_deploy does not call warn_leftover_authkey"
grep -A1 '^  url="$(public_url)"$' deploy.sh | grep -q '^  warn_leftover_authkey$' ||
  fail "the warning must come right after the URL (the node is logged in)"
authkey_case() { # authkey_case <local line> <remote line> <expected: none|local|remote|both>
  printf 'A=1\n%s\n' "$1" >"$WORK/local/.env.jetson"
  printf 'A=1\n%s\n' "$2" >"$JHOME/jobapp/.env"
  run 0 dfun warn_leftover_authkey
  no_secret
  case "$3" in
    none) [[ ! -s "$WORK/out" ]] || fail "warned for '$1' / '$2': $(cat "$WORK/out")" ;;
    local) out_has "TS_AUTHKEY is still set in .env.jetson although" ;;
    remote) out_has "TS_AUTHKEY is still set in fakejetson:jobapp/.env although" ;;
    both) out_has "TS_AUTHKEY is still set in .env.jetson fakejetson:jobapp/.env although" ;;
  esac
}
authkey_case "TS_AUTHKEY=" "TS_AUTHKEY=" none
authkey_case "# TS_AUTHKEY=tskey-$CANARY" "TS_HOSTNAME=jobapp" none
authkey_case 'TS_AUTHKEY=""' "TS_AUTHKEY= # removed" none
authkey_case "TS_AUTHKEY=tskey-auth-$CANARY" "TS_AUTHKEY=" local
authkey_case "TS_AUTHKEY=" "TS_AUTHKEY=\"tskey-auth-$CANARY\"" remote
authkey_case "TS_AUTHKEY='tskey-$CANARY'" "TS_AUTHKEY=tskey-auth-$CANARY" both
rm "$JHOME/jobapp/.env"
authkey_case "TS_AUTHKEY=" "TS_AUTHKEY=" none
ok "empty, commented or quoted-empty keys pass; a key in .env.jetson, the Jetson's .env or both is warned about by place, without its value"

step "tests/jetson_smoke.sh: the .env check, and the TS_AUTHKEY warning's grep"
grep -qF 'r "bash -s -- $RDIR/.env .env" <"$(dirname "$0")/../ops/env_check.sh"' tests/jetson_smoke.sh ||
  fail "jetson_smoke.sh does not stream ops/env_check.sh to the Jetson"
raw="$(sed -n 's/^if r "\(grep -Eq .*TS_AUTHKEY.*\)"; then$/\1/p' tests/jetson_smoke.sh)"
[[ -n "$raw" ]] || fail "no TS_AUTHKEY grep in jetson_smoke.sh"
smoke_grep() { # the smoke's remote command, expanded as its double quotes expand it, on <file>
  local cmd
  eval "cmd=\"${raw//\$RDIR\/.env/$1}\""
  bash -c "$cmd"
}
printf 'TS_AUTHKEY="tskey-%s"\n' "$CANARY" >"$WORK/smoke1.env"
printf "TS_AUTHKEY='tskey'\n" >"$WORK/smoke2.env"
printf 'TS_AUTHKEY=\n#TS_AUTHKEY=x\n' >"$WORK/smoke3.env"
smoke_grep "$WORK/smoke1.env" || fail "smoke grep missed a double-quoted key"
smoke_grep "$WORK/smoke2.env" || fail "smoke grep missed a single-quoted key"
if smoke_grep "$WORK/smoke3.env"; then fail "smoke grep matched an empty or commented key"; fi
ok "the smoke streams the check to the Jetson; its TS_AUTHKEY grep finds quoted keys and ignores empty or commented ones"

step "deploy.yml: the .env check before the build; the rollback trap from the sync until the new stack is up"
yml=.github/workflows/deploy.yml
line_of() { grep -nF -- "$1" "$yml" | head -n 1 | cut -d: -f1 || true; }
check="$(line_of 'bash ops/env_check.sh "$app/.env" "$app/.env"')"
build="$(line_of '::group::build')"
sync="$(line_of 'rsync -a --delete --exclude-from=.rsyncignore')"
trap_on="$(line_of "trap 'echo \"::error::a deploy command failed")"
trap_off="$(line_of 'trap - ERR')"
backup="$(line_of '::group::backup before migrations')"
# Issue #81: the migrations run in a one off container before compose up, the trap still set.
# Their output goes to the logs folder (MIGRATE_LOG_DIR), so the call carries that variable.
migrations="$(line_of 'bash ops/migrate.sh; then')"
up="$(line_of 'up -d --remove-orphans --wait --wait-timeout 180 || rollback')"
for v in check build sync trap_on trap_off backup migrations up; do
  [[ -n "${!v}" ]] || fail "deploy.yml: $v not found"
done
((check < build && trap_on < sync && sync < build && trap_on < backup && backup < migrations && migrations < up && up < trap_off)) ||
  fail "deploy.yml order: check $check build $build sync $sync trap $trap_on backup $backup migrations $migrations up $up untrap $trap_off"
# trap - ERR is the line just before the smoke group (the first match of tests/jetson_smoke.sh is
# in the header comment, so look for the step's own line).
# The step's own line carries JETSON_SMOKE_LOG (its detail goes to the logs folder).
smoke_run="$(line_of 'DEPLOY_HOST=local JETSON_SMOKE_FULL=0 JETSON_SMOKE_LOG=')"
[[ -n "$smoke_run" ]] || fail "deploy.yml: the smoke run not found"
((trap_off < smoke_run)) || fail "the trap is still set when the smoke runs"
grep -qF 'reported no backup file"; restore_previous; exit 1;' "$yml" || fail "the explicit backup failure does not restore"
grep -qF 'a smoke that fails after that does NOT roll back, on purpose' "$yml" || fail "header lacks the no-rollback note"
grep -qF '::warning::the api is not running' "$yml" || fail "no warning for an api that is not running"
ok "env check before the build; ERR trap set after the tree is saved and before the rsync, the backup before the migrations, the migrations before compose up, the trap cleared after compose up and before the smoke; header and api warning present"

printf '\nAll %d checks passed.\n' "$passed"
