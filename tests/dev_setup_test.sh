for args in "" "$URL" "$URL doing platform" "$URL doing platform now extra" \
  "$URL started platform now" "$URL doing Platform now" "$URL doing security now" "$URL doing platform soon" \
  "https://github.com/someone/jobapp/issues/1 doing platform now" "https://example.org/x doing platform now" \
  "https://github.com/GoldLegendW80/jobapp/issues/ doing platform now"; do
  # shellcheck disable=SC2086
  card 64 $args
  [[ ! -s "$CALLS" ]] || fail "card.sh $args called gh: $(cat "$CALLS")"
