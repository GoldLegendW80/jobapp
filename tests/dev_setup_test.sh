"auth status")
  [[ -z "${FAKE_GH_SIGNED_OUT:-}" ]] || { echo "You are not logged into any GitHub hosts." >&2; exit 1; }
  echo "github.com"
  echo "  ✓ Logged in to github.com account e2e-someone (keyring)"
  echo "  - Token: gho_FAKETOKEN0123456789abcdefFAKE"
  [[ -n "${FAKE_GH_NO_SCOPES:-}" ]] || echo "  - Token scopes: ${FAKE_GH_SCOPES-'gist', 'project', 'read:org', 'repo', 'workflow'}"
  ;;
"project item-add") echo "PVTI_fakeitem" ;;
esac
exit 0
EOF
fake docker <<'EOF'
#!/usr/bin/env bash
printf 'docker %s\n' "$*" >>"$CALLS"
case "$1" in
info) [[ -z "${FAKE_DOCKER_DOWN:-}" ]] || exit 1 ;;
image) [[ -n "${FAKE_SC_LOCAL:-}" ]] || exit 1 ;;
manifest) [[ -z "${FAKE_SC_UNREACHABLE:-}" ]] || exit 1 ;;
esac
exit 0
EOF
fake uv <<'EOF'
