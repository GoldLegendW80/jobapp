EOF
fake pnpm <<'EOF'
#!/usr/bin/env bash
printf 'pnpm %s (in %s, switch %s, on fail %s)\n' "$*" "$PWD" "${npm_config_manage_package_manager_versions:-on}" "${pnpm_config_pm_on_fail:-download}" >>"$CALLS"
echo "${FAKE_PNPM_VERSION:-9.15.9}"
EOF
fake python3 <<'EOF'
#!/usr/bin/env bash
