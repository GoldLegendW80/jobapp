  if [[ -n "${FAKE_SSH_NO_ALIAS:-}" ]]; then echo "hostname $2"; else echo "hostname 100.64.0.99"; fi
  echo "user someone"
  exit 0
fi
[[ -z "${FAKE_SSH_FAILS:-}" ]] || exit 255
exit 0
EOF
fake claude <<'EOF'
#!/usr/bin/env bash
printf 'claude %s\n' "$*" >>"$CALLS"
echo "2.1.0 (Claude Code)"
EOF
export CALLS
export PATH="$BIN:$SYS"
unset FAKE_GH_SIGNED_OUT FAKE_GH_NO_SCOPES FAKE_GH_SCOPES FAKE_DOCKER_DOWN FAKE_SC_LOCAL FAKE_SC_UNREACHABLE \
  FAKE_NODE_VERSION FAKE_PNPM_VERSION FAKE_PYTHON_VERSION FAKE_SSH_NO_ALIAS FAKE_SSH_FAILS \
  DEV_SETUP_JETSON_ALIAS
export DEV_SETUP_MIN_FREE_GIB=0

# The hook pre-commit install writes (its first lines name pre-commit).
install_hook() {
  mkdir -p "$REPO/.git/hooks"
  printf '#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\n' >"$REPO/.git/hooks/pre-commit"
}
install_hook

# run <expected exit> [script arguments ...]: dev-setup.sh, output in $WORK/out
run() {
  local want="$1" got=0
  shift
  : >"$CALLS"
  "$REPO/ops/dev-setup.sh" "$@" >"$WORK/out" 2>&1 || got=$?
  [[ "$got" == "$want" ]] || fail "dev-setup.sh $* exited $got, expected $want: $(cat "$WORK/out")"
}
out_has() { grep -qF -- "$1" "$WORK/out" || fail "output lacks '$1': $(cat "$WORK/out")"; }
out_lacks() { if grep -qF -- "$1" "$WORK/out"; then fail "output has '$1': $(cat "$WORK/out")"; fi; }
last_line_is() {
  local last
  last="$(tail -n 1 "$WORK/out")"
  [[ "$last" == "$1" ]] || fail "last line is '$last', expected '$1'"
}
misses() { # misses <n>: exactly n MISS lines and the matching last line
  local n
  n="$(grep -c '^MISS ' "$WORK/out" || true)"
  [[ "$n" == "$1" ]] || fail "$n MISS lines, expected $1: $(cat "$WORK/out")"
  last_line_is "DEV SETUP: $1 missing"
}
calls_lack() { if grep -qE -- "$1" "$CALLS"; then fail "a call matches '$1': $(cat "$CALLS")"; fi; }
# The one pnpm call: its version, from / (no packageManager above) with both version switches off.
pnpm_asked_from_root() {
  local want='pnpm --version (in /, switch false, on fail ignore)' others
  grep -qxF "$want" "$CALLS" || fail "pnpm --version not asked from / with the switches off: $(cat "$CALLS")"
  others="$(grep '^pnpm ' "$CALLS" | grep -vxF "$want" || true)"
  [[ -z "$others" ]] || fail "another pnpm call: $others"
}

