#!/usr/bin/env bash
# Tests of the two helper scripts of the development workflow: ops/dev-setup.sh (what a new
# laptop needs, read only) and ops/card.sh (a card on the project board). Every tool they call is
# a fake on a PATH that holds nothing else but a few system utilities, and writes what it was
# asked into a log: nothing is installed, pulled, signed in, connected or sent.
#
#   tests/dev_setup_test.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="$(mktemp -d)"
WORK="$(cd "$WORK" && pwd -P)"
trap 'rm -rf "$WORK"' EXIT

passed=0
ok() {
  passed=$((passed + 1))
  printf 'ok   %s\n' "$*"
}
fail() {
  printf 'FAIL %s\n' "$*" >&2
  exit 1
}

# A throwaway clone: the two scripts and a web/package.json like the real one.
REPO="$WORK/repo"
mkdir -p "$REPO/ops" "$REPO/web"
cp "$ROOT/ops/dev-setup.sh" "$ROOT/ops/card.sh" "$REPO/ops/"
cat >"$REPO/web/package.json" <<'EOF'
{
  "name": "web",
  "packageManager": "pnpm@9.15.9",
  "engines": {
    "node": ">=22.12.0"
  }
}
EOF
git -C "$REPO" init -q -b main

# The system utilities the scripts may use, alone on PATH with the fakes: a tool the fakes do
# not provide is missing, whatever this machine has installed.
SYS="$WORK/sys"
mkdir -p "$SYS"
for tool in bash env sh grep sed awk df git tr head tail cat dirname mkdir mktemp mv chmod rm; do
  ln -s "$(command -v "$tool")" "$SYS/$tool"
done

BIN="$WORK/bin"
mkdir -p "$BIN"
CALLS="$WORK/calls"
# A fake that logs its call, then answers from FAKE_<NAME>_* settings.
fake() {
  cat >"$BIN/$1"
  chmod +x "$BIN/$1"
}
